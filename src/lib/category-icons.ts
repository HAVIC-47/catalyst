/** The icon name a category shows: its own (when it's one of ours), else one picked from its name. */
export function categoryIconName(name: string, icon?: string | null): string {
  if (icon && icon in CATEGORY_ICONS) return icon;
  return AUTO.find(([re]) => re.test(name))?.[1] ?? "tag";
}

export function categoryIcon(name: string, icon?: string | null): LucideIcon {
  return CATEGORY_ICONS[categoryIconName(name, icon)];
}
